/** The name of a Morse relay chain id (any case), or null when the map has none. */
export function morseChainName(id: string): string | null {
  return NAMES[id.toUpperCase()] ?? null;
}

/** "Ethereum (F00C)", or the bare id when the chain has no name. */
export function morseChainLabel(id: string): string {
  const name = morseChainName(id);
  return name ? `${name} (${id.toUpperCase()})` : id.toUpperCase();
}
